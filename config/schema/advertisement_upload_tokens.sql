ALTER TABLE post_advertisement
    ADD COLUMN IF NOT EXISTS submission_key UUID,
    ADD COLUMN IF NOT EXISTS submission_fingerprint CHAR(64);

CREATE UNIQUE INDEX IF NOT EXISTS uq_post_advertisement_submission_key
    ON post_advertisement (submission_key)
    WHERE submission_key IS NOT NULL;

DO $$
BEGIN
    IF EXISTS (
        SELECT 1
        FROM post_advertisement_vacancies
        WHERE post_id IS NOT NULL
        GROUP BY post_advertisement_id, post_id
        HAVING COUNT(*) > 1
    ) THEN
        RAISE EXCEPTION 'Duplicate post_advertisement_vacancies rows exist; clean them before applying the unique index';
    END IF;
END $$;

CREATE UNIQUE INDEX IF NOT EXISTS uq_post_advertisement_vacancies_application_post
    ON post_advertisement_vacancies (post_advertisement_id, post_id)
    WHERE post_id IS NOT NULL;

CREATE TABLE IF NOT EXISTS post_advertisement_upload_tokens (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    token CHAR(64) NOT NULL UNIQUE,
    client_upload_id UUID NOT NULL,
    user_id TEXT NOT NULL,
    sanstha_code TEXT NOT NULL,
    document_type VARCHAR(32) NOT NULL CHECK (
        document_type IN (
            'advApprovelFile',
            'resolutionFile',
            'CADetailsFile',
            'periodFile',
            'period2324File',
            'sanch_manyata',
            'smDetailsFile'
        )
    ),
    udise_code TEXT,
    storage_key TEXT NOT NULL UNIQUE,
    file_size INTEGER NOT NULL CHECK (file_size BETWEEN 1 AND 2097152),
    content_sha256 CHAR(64) NOT NULL,
    status VARCHAR(20) NOT NULL DEFAULT 'uploaded' CHECK (
        status IN ('uploaded', 'consumed', 'cleanup_pending')
    ),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    expires_at TIMESTAMPTZ NOT NULL,
    consumed_at TIMESTAMPTZ,
    post_advertisement_id TEXT,
    CONSTRAINT ck_post_advertisement_upload_udise CHECK (
        (document_type IN ('sanch_manyata', 'smDetailsFile') AND udise_code IS NOT NULL)
        OR (document_type NOT IN ('sanch_manyata', 'smDetailsFile') AND udise_code IS NULL)
    ),
    CONSTRAINT uq_post_advertisement_upload_client_id
        UNIQUE (user_id, sanstha_code, client_upload_id)
);

CREATE INDEX IF NOT EXISTS ix_post_advertisement_upload_expiry
    ON post_advertisement_upload_tokens (status, expires_at);

CREATE INDEX IF NOT EXISTS ix_post_advertisement_upload_owner
    ON post_advertisement_upload_tokens (user_id, sanstha_code, token);
